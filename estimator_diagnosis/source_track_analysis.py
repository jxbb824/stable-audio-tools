#!/usr/bin/env python3
"""Can each estimator find the training track whose metadata was used as the query prompt?

Each query q was generated by model 0 from a prompt built from one training track's metadata
(prompt_manifest.json: source_track_id / source_seller_id). This gives a GT-free sanity check at
track level plus a seller-level check that targets the only strong seller-specific signal in a*.
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd
import torch
from scipy.stats import rankdata, spearmanr

ROOT = Path("/ocean/projects/mth260005p/xjiang6/stable-audio-tools")
OUT = ROOT / "sao_ip_100/outputs"
DIAG = ROOT / "estimator_diagnosis"
res = {}

items = json.load(open(OUT / "generated_queries/prompt_manifest.json"))["items"]
by_file = {it["filename"]: it for it in items}
sellers = pd.read_csv(OUT / "selection/seller_manifest.csv")
seller_ids = list(sellers["seller_id"])
sidx = {s: i for i, s in enumerate(seller_ids)}
ntr = np.array(sellers["selected_tracks"])
cat = pd.read_csv(OUT / "selection/category_manifest.csv")
rel2seller = dict(zip(cat["relpath"], cat["seller_id"]))

# canonical axes = D-TRAK chunked run axes (baselines use them too)
tman = pd.read_csv(OUT / "dtrak_attribution_v100_chunked/train_axis_manifest.csv")
qman = pd.read_csv(OUT / "dtrak_attribution_v100_chunked/query_axis_manifest.csv")
t_rel = tman["relpath"].tolist()
t_seller = np.array([sidx[rel2seller[r]] for r in t_rel])
q_files = qman["filename"].tolist()
src_track_rel = [by_file[f]["source_relpath"] for f in q_files]
src_track_idx = np.array([t_rel.index(r) if r in t_rel else -1 for r in src_track_rel])
src_seller_idx = np.array([sidx[by_file[f]["source_seller_id"]] for f in q_files])
res["queries_with_source_track_in_train_axis"] = int((src_track_idx >= 0).sum())

# size-proportional chance of hitting the source seller when picking a seller at random w.p. ~ size
p = ntr / ntr.sum()
res["chance_top1_uniform"] = 1 / len(seller_ids)
res["chance_top1_size_proportional"] = float((p[src_seller_idx]).mean())


def load_scores():
    out = {}
    out["dtrak_chunked_lam0.1"] = np.array(np.memmap(OUT / "dtrak_attribution_v100_chunked/scores_query_x_train.memmap",
                                                     dtype=np.float32, mode="r", shape=(200, 1117))).T
    # 6h run: its own axes (check they match canonical)
    t6 = pd.read_csv(OUT / "dtrak_attribution_6h/train_axis_manifest.csv")["relpath"].tolist()
    q6 = pd.read_csv(OUT / "dtrak_attribution_6h/query_axis_manifest.csv")["filename"].tolist()
    S6 = np.array(np.memmap(OUT / "dtrak_attribution_6h/scores_query_x_train.memmap",
                            dtype=np.float32, mode="r", shape=(200, 1117))).T
    S6 = S6[[t6.index(r) for r in t_rel]][:, [q6.index(f) for f in q_files]]
    out["dtrak_6h_lam0.1"] = S6
    E = torch.load(OUT / "ekfac_attribution_v100_layer_sharded/scores_train_x_query.pt").numpy()
    te = pd.read_csv(OUT / "ekfac_attribution_v100_layer_sharded/train_axis_manifest.csv")["relpath"].tolist()
    qe = pd.read_csv(OUT / "ekfac_attribution_v100_layer_sharded/query_axis_manifest.csv")["filename"].tolist()
    out["ekfac"] = E[[te.index(r) for r in t_rel]][:, [qe.index(f) for f in q_files]]
    for b in ["clap", "fingerprint", "random"]:
        out[b] = torch.load(OUT / f"baselines/{b}/score_{b}.pt").numpy()
    # D-TRAK re-scored with other lambdas from saved features (chunked run)
    d = OUT / "dtrak_attribution_v100_chunked/members/single"
    X = np.array(np.memmap(d / "train_features_raw.memmap", dtype=np.float32, mode="r", shape=(1117, 2048)), dtype=np.float64)
    Xq = np.array(np.memmap(d / "query_features.memmap", dtype=np.float32, mode="r", shape=(200, 2048)), dtype=np.float64)
    tid = [("/".join(t.split("/")[-2:])) for t in (d / "train_features_raw.memmap.ids.txt").read_text().splitlines()]
    qid = [Path(q).name for q in (d / "query_features.memmap.ids.txt").read_text().splitlines()]
    tp = [tid.index(r) for r in t_rel]
    qp = [qid.index(f) for f in q_files]
    X, Xq = X[tp], Xq[qp]
    for lam in [1e1, 1e3, 1e5]:
        out[f"dtrak_chunked_lam{lam:.0e}"] = (Xq @ np.linalg.inv(X.T @ X + lam * np.eye(2048)) @ X.T).T
    out["dtrak_chunked_rawdot"] = (Xq @ X.T).T
    Xn = X / np.linalg.norm(X, axis=1, keepdims=True)
    Qn = Xq / np.linalg.norm(Xq, axis=1, keepdims=True)
    out["dtrak_chunked_cosine"] = (Qn @ Xn.T).T
    return out


scores = load_scores()
for name, T in scores.items():  # T: [1117 train, 200 query]
    ok = src_track_idx >= 0
    tr_rank = np.array([rankdata(-T[:, q])[src_track_idx[q]] for q in np.where(ok)[0]])
    res[f"{name}_source_TRACK_median_rank_of_1117"] = float(np.median(tr_rank))
    res[f"{name}_source_TRACK_top1"] = float((tr_rank <= 1).mean())
    res[f"{name}_source_TRACK_top10"] = float((tr_rank <= 10).mean())
    for agg in ["sum", "mean"]:
        M = np.zeros((len(seller_ids), T.shape[1]))
        np.add.at(M, t_seller, T)
        if agg == "mean":
            M = M / ntr[:, None]
        sr = np.array([rankdata(-M[:, q])[src_seller_idx[q]] for q in range(T.shape[1])])
        res[f"{name}_source_SELLER_top1_{agg}"] = float((sr <= 1).mean())
        res[f"{name}_source_SELLER_mean_rank_{agg}"] = float(sr.mean())

json.dump(res, open(DIAG / "source_track_analysis_results.json", "w"), indent=2)
for k, v in res.items():
    print(f"{k}: {v:.4f}" if isinstance(v, float) else f"{k}: {v}")
